"""Generates src/content/approved.ts from reference/approved-draft.html.

The approved public pages keep their original markup. This script copies the Home and About
sections, maps the image placeholders to real asset paths and turns hash links into site routes.
Run from the client folder: python3 scripts/generate-approved.py
"""
import json
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
source = (root / 'reference' / 'approved-draft.html').read_text(encoding='utf-8')

ASSETS = {'logo': '/assets/logo.webp', 'iso': '/assets/iso.webp'}


def section(name: str) -> str:
    match = re.search(r'<section data-view="%s"[^>]*>.*?</section>' % name, source, re.S)
    if not match:
        raise SystemExit(f'Section "{name}" was not found in the approved draft.')
    html = match.group(0)
    html = re.sub(r'\s*data-view="[^"]*"', '', html, count=1)
    html = re.sub(r'data-a="(logo|iso)"', lambda m: f'src="{ASSETS[m.group(1)]}"', html)
    html = re.sub(r'href="#([a-z-]+)"', r'href="/\1"', html)
    return html


out = {'home': section('home'), 'about': section('about')}
body = 'export const APPROVED_HTML = ' + json.dumps(out, indent=2, ensure_ascii=False) + ' as const;\n'
header = ('// GENERATED by scripts/generate-approved.py from reference/approved-draft.html. Do not edit by hand.\n')
(root / 'src' / 'content' / 'approved.ts').write_text(header + body, encoding='utf-8')
print('Wrote src/content/approved.ts')
